package webserver

import (
	"bytes"
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"text/template"

	"github.com/seintech/panel/internal/core/system"
	"github.com/seintech/panel/internal/model"
)

type OpenLiteSpeedServer struct {
	sm       *system.ServiceManager
	vhostDir string
}

func NewOpenLiteSpeedServer(sm *system.ServiceManager) *OpenLiteSpeedServer {
	return &OpenLiteSpeedServer{
		sm:       sm,
		vhostDir: "/usr/local/lsws/conf/vhosts",
	}
}

func (o *OpenLiteSpeedServer) Type() model.WebServerType {
	return model.WebServerOLS
}

func (o *OpenLiteSpeedServer) Name() string {
	return "OpenLiteSpeed"
}

func (o *OpenLiteSpeedServer) ConfigPath(domain *model.Domain) string {
	return filepath.Join(o.vhostDir, domain.DomainName, "vhconf.conf")
}

const olsVHostTemplate = `# Auto-generated by Seintech Panel for {{ .DomainName }}
docRoot                   {{ .DocumentRoot }}
vhDomain                  {{ .DomainName }}
{{- if .Aliases }}
vhAliases                 {{ range .Aliases }}{{ . }}, {{ end }}
{{- end }}
adminEmails               admin@{{ .DomainName }}
enableGzip                1

errorlog /usr/local/lsws/logs/{{ .DomainName }}.error.log {
  useServer               0
  logLevel                DEBUG
  rollingSize             10M
}

accesslog /usr/local/lsws/logs/{{ .DomainName }}.access.log {
  useServer               0
  rollingSize             10M
  keepDays                30
  compressArchive         1
}

index  {
  useServer               0
  indexFiles              index.php, index.html
  autoIndex               0
}

{{- if .IsReverseProxy }}
context / {
  type                    proxy
  handler                 proxy_{{ .ID }}
  addDefaultCharset       off
}
{{- else if not .IsStatic }}
scripthandler  {
  add                     fcgi:php-{{ .DomainName }} php
}

extprocessor php-{{ .DomainName }} {
  type                    fcgi
  address                 uds://{{ .PHPSocket }}
  maxConns                35
  initTimeout             60
  retryTimeout            0
  persistConn             1
  respBuffer              0
}
{{- end }}

{{- if .SSLEnabled }}
vhssl  {
  keyFile                 {{ .SSLKeyPath }}
  certFile                {{ .SSLCertPath }}
  certChain               1
  sslProtocol             24
}
{{- end }}
`

func (o *OpenLiteSpeedServer) GenerateVHost(ctx context.Context, domain *model.Domain) error {
	tmpl, err := template.New("ols").Parse(olsVHostTemplate)
	if err != nil {
		return fmt.Errorf("template parse error: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, domain); err != nil {
		return fmt.Errorf("template execute error: %w", err)
	}

	confFile := o.ConfigPath(domain)
	dir := filepath.Dir(confFile)
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}

	return os.WriteFile(confFile, buf.Bytes(), 0644)
}

func (o *OpenLiteSpeedServer) RemoveVHost(ctx context.Context, domain *model.Domain) error {
	dir := filepath.Dir(o.ConfigPath(domain))
	return os.RemoveAll(dir)
}

func (o *OpenLiteSpeedServer) TestConfig(ctx context.Context) (string, error) {
	cmd := exec.CommandContext(ctx, "/usr/local/lsws/bin/lswsctrl", "test")
	out, err := cmd.CombinedOutput()
	return string(out), err
}

func (o *OpenLiteSpeedServer) Reload(ctx context.Context) error {
	return o.sm.Reload(ctx, "lsws")
}

func (o *OpenLiteSpeedServer) Restart(ctx context.Context) error {
	return o.sm.Restart(ctx, "lsws")
}

func (o *OpenLiteSpeedServer) Status(ctx context.Context) (system.ServiceState, error) {
	return o.sm.GetStatus(ctx, "lsws")
}
