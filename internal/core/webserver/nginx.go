package webserver

import (
	"bytes"
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"text/template"

	"github.com/seintech/panel/internal/core/system"
	"github.com/seintech/panel/internal/model"
)

type NginxServer struct {
	sm           *system.ServiceManager
	availableDir string
	enabledDir   string
}

func NewNginxServer(sm *system.ServiceManager) *NginxServer {
	return &NginxServer{
		sm:           sm,
		availableDir: "/etc/nginx/sites-available",
		enabledDir:   "/etc/nginx/sites-enabled",
	}
}

func (n *NginxServer) Type() model.WebServerType {
	return model.WebServerNginx
}

func (n *NginxServer) Name() string {
	return "Nginx"
}

func (n *NginxServer) ConfigPath(domain *model.Domain) string {
	return filepath.Join(n.availableDir, domain.DomainName+".conf")
}

const nginxVHostTemplate = `# Auto-generated by Seintech Panel for {{ .DomainName }}
# Created at: {{ .CreatedAt }}

{{- if .SSLEnabled }}
# HTTP Redirect to HTTPS
server {
    listen 80;
    listen [::]:80;
    server_name {{ .DomainName }} {{ range .Aliases }}{{ . }} {{ end }};

    # Let's Encrypt ACME Challenge Rule
    location /.well-known/acme-challenge/ {
        root /var/lib/seintech/acme-challenge;
        try_files $uri =404;
    }

    location / {
        return 301 https://$host$request_uri;
    }
}
{{- end }}

server {
    {{- if .SSLEnabled }}
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    ssl_certificate {{ .SSLCertPath }};
    ssl_certificate_key {{ .SSLKeyPath }};
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers HIGH:!aNULL:!MD5;
    ssl_prefer_server_ciphers on;
    {{- else }}
    listen 80;
    listen [::]:80;
    {{- end }}

    server_name {{ .DomainName }} {{ range .Aliases }}{{ . }} {{ end }};
    root {{ .DocumentRoot }};
    index index.php index.html index.htm;

    access_log /var/log/nginx/{{ .DomainName }}.access.log;
    error_log /var/log/nginx/{{ .DomainName }}.error.log;

    # Security Headers
    add_header X-Frame-Options "SAMEORIGIN" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header X-XSS-Protection "1; mode=block" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;

    # ACME Challenge
    location /.well-known/acme-challenge/ {
        root /var/lib/seintech/acme-challenge;
        try_files $uri =404;
    }

    {{- if .IsReverseProxy }}
    # Reverse Proxy Mode
    location / {
        proxy_pass {{ .ProxyTarget }};
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
    }
    {{- else if .IsStatic }}
    # Static Site Mode
    location / {
        try_files $uri $uri/ /index.html =404;
    }
    {{- else }}
    # PHP-FPM FastCGI Mode
    location / {
        try_files $uri $uri/ /index.php?$query_string;
    }

    location ~ \.php$ {
        include snippets/fastcgi-php.conf;
        fastcgi_pass unix:{{ .PHPSocket }};
        fastcgi_param SCRIPT_FILENAME $realpath_root$fastcgi_script_name;
        include fastcgi_params;
    }
    {{- end }}

    location ~ /\.(?!well-known).* {
        deny all;
    }
}
`

func (n *NginxServer) GenerateVHost(ctx context.Context, domain *model.Domain) error {
	tmpl, err := template.New("nginx").Parse(nginxVHostTemplate)
	if err != nil {
		return fmt.Errorf("template parse error: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, domain); err != nil {
		return fmt.Errorf("template execute error: %w", err)
	}

	_ = os.MkdirAll(n.availableDir, 0755)
	_ = os.MkdirAll(n.enabledDir, 0755)

	availFile := n.ConfigPath(domain)
	if err := os.WriteFile(availFile, buf.Bytes(), 0644); err != nil {
		return fmt.Errorf("writing nginx config failed: %w", err)
	}

	// Symlink to sites-enabled
	enabledFile := filepath.Join(n.enabledDir, domain.DomainName+".conf")
	_ = os.Remove(enabledFile)
	if err := os.Symlink(availFile, enabledFile); err != nil {
		// If symlink fails, copy file as fallback
		_ = os.WriteFile(enabledFile, buf.Bytes(), 0644)
	}

	return nil
}

func (n *NginxServer) RemoveVHost(ctx context.Context, domain *model.Domain) error {
	availFile := n.ConfigPath(domain)
	enabledFile := filepath.Join(n.enabledDir, domain.DomainName+".conf")

	_ = os.Remove(enabledFile)
	return os.Remove(availFile)
}

func (n *NginxServer) TestConfig(ctx context.Context) (string, error) {
	cmd := exec.CommandContext(ctx, "nginx", "-t")
	out, err := cmd.CombinedOutput()
	return string(out), err
}

func (n *NginxServer) Reload(ctx context.Context) error {
	return n.sm.Reload(ctx, "nginx")
}

func (n *NginxServer) Restart(ctx context.Context) error {
	return n.sm.Restart(ctx, "nginx")
}

func (n *NginxServer) Status(ctx context.Context) (system.ServiceState, error) {
	return n.sm.GetStatus(ctx, "nginx")
}
