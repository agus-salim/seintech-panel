package webserver

import (
	"bytes"
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"text/template"

	"github.com/seintech/panel/internal/core/system"
	"github.com/seintech/panel/internal/model"
)

type ApacheServer struct {
	sm           *system.ServiceManager
	availableDir string
	enabledDir   string
}

func NewApacheServer(sm *system.ServiceManager) *ApacheServer {
	return &ApacheServer{
		sm:           sm,
		availableDir: "/etc/apache2/sites-available",
		enabledDir:   "/etc/apache2/sites-enabled",
	}
}

func (a *ApacheServer) Type() model.WebServerType {
	return model.WebServerApache
}

func (a *ApacheServer) Name() string {
	return "Apache2"
}

func (a *ApacheServer) ConfigPath(domain *model.Domain) string {
	return filepath.Join(a.availableDir, domain.DomainName+".conf")
}

const apacheVHostTemplate = `# Auto-generated by Seintech Panel (Backend) for {{ .DomainName }}
<VirtualHost 127.0.0.1:8080 [::1]:8080 *:8080>
    ServerName {{ .DomainName }}
    {{- range .Aliases }}
    ServerAlias {{ . }}
    {{- end }}
    ServerAdmin webmaster@{{ .DomainName }}
    DocumentRoot {{ .DocumentRoot }}
    DirectoryIndex index.php index.html index.htm

    # Trust Nginx Forwarded HTTPS Protocol
    SetEnvIf X-Forwarded-Proto "^https$" HTTPS=on

    # Let's Encrypt ACME Challenge
    Alias /.well-known/acme-challenge/ /var/lib/seintech/acme-challenge/
    <Directory "/var/lib/seintech/acme-challenge/">
        Options None
        AllowOverride None
        Require all granted
    </Directory>

    <Directory "{{ .DocumentRoot }}">
        Options -Indexes +FollowSymLinks
        AllowOverride All
        Require all granted
    </Directory>

    {{- if .IsReverseProxy }}
    ProxyPreserveHost On
    ProxyPass / {{ .ProxyTarget }}/
    ProxyPassReverse / {{ .ProxyTarget }}/
    {{- else if not .IsStatic }}
    <FilesMatch \.php$>
        SetHandler "proxy:unix:{{ .PHPSocket }}|fcgi://localhost/"
    </FilesMatch>
    {{- end }}

    ErrorLog ${APACHE_LOG_DIR}/{{ .DomainName }}_error.log
    CustomLog ${APACHE_LOG_DIR}/{{ .DomainName }}_access.log combined
</VirtualHost>
`

func (a *ApacheServer) GenerateVHost(ctx context.Context, domain *model.Domain) error {
	tmpl, err := template.New("apache").Parse(apacheVHostTemplate)
	if err != nil {
		return fmt.Errorf("template parse error: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, domain); err != nil {
		return fmt.Errorf("template execute error: %w", err)
	}

	_ = os.MkdirAll(a.availableDir, 0755)
	_ = os.MkdirAll(a.enabledDir, 0755)

	availFile := a.ConfigPath(domain)
	if err := os.WriteFile(availFile, buf.Bytes(), 0644); err != nil {
		return fmt.Errorf("writing apache config failed: %w", err)
	}

	enabledFile := filepath.Join(a.enabledDir, domain.DomainName+".conf")
	_ = os.Remove(enabledFile)
	if err := os.Symlink(availFile, enabledFile); err != nil {
		_ = os.WriteFile(enabledFile, buf.Bytes(), 0644)
	}

	return nil
}

func (a *ApacheServer) RemoveVHost(ctx context.Context, domain *model.Domain) error {
	availFile := a.ConfigPath(domain)
	enabledFile := filepath.Join(a.enabledDir, domain.DomainName+".conf")

	_ = os.Remove(enabledFile)
	return os.Remove(availFile)
}

func (a *ApacheServer) TestConfig(ctx context.Context) (string, error) {
	cmd := exec.CommandContext(ctx, "apachectl", "-t")
	out, err := cmd.CombinedOutput()
	return string(out), err
}

func (a *ApacheServer) Reload(ctx context.Context) error {
	return a.sm.Reload(ctx, "apache2")
}

func (a *ApacheServer) Restart(ctx context.Context) error {
	return a.sm.Restart(ctx, "apache2")
}

func (a *ApacheServer) Status(ctx context.Context) (system.ServiceState, error) {
	return a.sm.GetStatus(ctx, "apache2")
}
