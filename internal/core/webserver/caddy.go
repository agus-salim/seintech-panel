package webserver

import (
	"bytes"
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"text/template"

	"github.com/seintech/panel/internal/core/system"
	"github.com/seintech/panel/internal/model"
)

type CaddyServer struct {
	sm      *system.ServiceManager
	confDir string
}

func NewCaddyServer(sm *system.ServiceManager) *CaddyServer {
	return &CaddyServer{
		sm:      sm,
		confDir: "/etc/caddy/conf.d",
	}
}

func (c *CaddyServer) Type() model.WebServerType {
	return model.WebServerCaddy
}

func (c *CaddyServer) Name() string {
	return "Caddy"
}

func (c *CaddyServer) ConfigPath(domain *model.Domain) string {
	return filepath.Join(c.confDir, domain.DomainName+".caddy")
}

const caddyVHostTemplate = `# Auto-generated by Seintech Panel for {{ .DomainName }}
{{ .DomainName }}{{ range .Aliases }}, {{ . }}{{ end }} {
    root * {{ .DocumentRoot }}
    encode gzip zstd

    # Security Headers
    header {
        X-Frame-Options "SAMEORIGIN"
        X-Content-Type-Options "nosniff"
        Referrer-Policy "strict-origin-when-cross-origin"
    }

    {{- if .SSLEnabled }}
    {{- if eq .SSLProvider "custom" }}
    tls {{ .SSLCertPath }} {{ .SSLKeyPath }}
    {{- else if eq .SSLProvider "letsencrypt" }}
    # Let's Encrypt automated ACME handled natively by Caddy
    {{- end }}
    {{- else }}
    # Plain HTTP
    auto_https off
    {{- end }}

    {{- if .IsReverseProxy }}
    reverse_proxy {{ .ProxyTarget }}
    {{- else if .IsStatic }}
    file_server
    try_files {path} {path}/ /index.html =404
    {{- else }}
    php_fastcgi unix/{{ .PHPSocket }}
    file_server
    {{- end }}

    log {
        output file /var/log/caddy/{{ .DomainName }}.log
    }
}
`

func (c *CaddyServer) GenerateVHost(ctx context.Context, domain *model.Domain) error {
	tmpl, err := template.New("caddy").Parse(caddyVHostTemplate)
	if err != nil {
		return fmt.Errorf("template parse error: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, domain); err != nil {
		return fmt.Errorf("template execute error: %w", err)
	}

	_ = os.MkdirAll(c.confDir, 0755)
	_ = os.MkdirAll("/var/log/caddy", 0755)

	confFile := c.ConfigPath(domain)
	return os.WriteFile(confFile, buf.Bytes(), 0644)
}

func (c *CaddyServer) RemoveVHost(ctx context.Context, domain *model.Domain) error {
	return os.Remove(c.ConfigPath(domain))
}

func (c *CaddyServer) TestConfig(ctx context.Context) (string, error) {
	cmd := exec.CommandContext(ctx, "caddy", "validate", "--adapter", "caddyfile", "--config", "/etc/caddy/Caddyfile")
	out, err := cmd.CombinedOutput()
	return string(out), err
}

func (c *CaddyServer) Reload(ctx context.Context) error {
	return c.sm.Reload(ctx, "caddy")
}

func (c *CaddyServer) Restart(ctx context.Context) error {
	return c.sm.Restart(ctx, "caddy")
}

func (c *CaddyServer) Status(ctx context.Context) (system.ServiceState, error) {
	return c.sm.GetStatus(ctx, "caddy")
}
